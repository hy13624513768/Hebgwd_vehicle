from __future__ import annotations

from typing import TypedDict


class TermDef(TypedDict, total=False):
    name: str
    aliases: list[str]
    keywords: list[str]
    remarks: str


class SubDef(TypedDict):
    name: str
    terms: list[TermDef]


class CategoryDef(TypedDict):
    code: str
    name: str
    children: list[SubDef]


def _t(name: str, *aliases: str, keywords: list[str] | None = None, remarks: str = "") -> TermDef:
    kw = list(keywords) if keywords else []
    for a in aliases:
        if a and a not in kw:
            kw.append(a)
    if name not in kw:
        kw.insert(0, name)
    return {
        "name": name,
        "aliases": list(aliases),
        "keywords": kw,
        "remarks": remarks,
    }


